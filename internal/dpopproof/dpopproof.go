// Package dpopproof builds and verifies DPoP proofs (RFC 9449) with internal/jose.
package dpopproof

import (
	"bytes"
	"context"
	"crypto/ecdsa"
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"net/url"
	"strconv"
	"strings"
	"time"

	"github.com/eclipse-xfsc/facis-zero-trust-demonstrator/internal/jose"
	"github.com/eclipse-xfsc/facis-zero-trust-demonstrator/internal/replay"
)

// Typ is the proof's typ header.
const Typ = "dpop+jwt"

// Key is a proof key whose private half is held elsewhere (OpenBao transit, or a process key).
type Key interface {
	JWK() jose.JWK
	Sign(ctx context.Context, signingInput []byte) ([]byte, error)
}

// Claims are the proof's claims. JTI is generated by Build when empty.
type Claims struct {
	JTI   string
	HTM   string
	HTU   string
	IAT   time.Time
	ATH   string // base64url SHA-256 of the access token, when the proof accompanies one
	Nonce string
}

// Expect is what the verifier checks the proof against.
type Expect struct {
	Method      string
	URI         string // the configured public URI of the request, never one taken from Host or forwarded headers
	AccessToken string // when set, ath must match it
	JKT         string // when set, the proof key's thumbprint must equal it
	Nonce       string // when set, the nonce must equal it
}

// Policy bounds the iat window.
type Policy struct {
	Lifespan time.Duration
	Skew     time.Duration
}

// Verified is a proof that passed.
type Verified struct {
	JKT      string
	Claims   Claims
	NotAfter time.Time
}

var (
	ErrInvalid  = errors.New("dpop: invalid proof")
	ErrMismatch = errors.New("dpop: proof does not match the request")
	ErrReplayed = errors.New("dpop: proof replayed")

	// ErrKeyMismatch is the ErrMismatch for a proof key whose thumbprint is not Expect.JKT.
	ErrKeyMismatch = fmt.Errorf("%w: proof key is not the bound key", ErrMismatch)
)

// Build signs a proof with key. A zero IAT means now.
func Build(ctx context.Context, key Key, c Claims) (string, error) {
	if c.JTI == "" {
		raw := make([]byte, 16)
		if _, err := rand.Read(raw); err != nil {
			return "", errors.New("dpop: generate jti")
		}
		c.JTI = base64.RawURLEncoding.EncodeToString(raw)
	}
	if c.IAT.IsZero() {
		c.IAT = time.Now()
	}
	payload, err := json.Marshal(wireClaims{JTI: c.JTI, HTM: c.HTM, HTU: c.HTU, IAT: c.IAT.Unix(), ATH: c.ATH, Nonce: c.Nonce})
	if err != nil {
		return "", errors.New("dpop: encode claims")
	}
	jwk := key.JWK()
	return jose.Sign(ctx, jose.Header{Typ: Typ, JWK: &jwk}, payload, key.Sign)
}

// Verify checks the proof against want and policy at now, then records it in store; a store error
// fails closed.
func Verify(ctx context.Context, proof string, want Expect, policy Policy, now time.Time, store replay.Store) (Verified, error) {
	if store == nil {
		return Verified{}, errors.New("dpop: no replay store")
	}
	if len(proof) > maxProofSize {
		return Verified{}, fmt.Errorf("%w: proof too large", ErrInvalid)
	}
	h, payload, err := jose.Verify(proof, jose.HeaderPolicy{Typ: Typ, JWKNeeded: true}, func(h jose.Header) (*ecdsa.PublicKey, error) {
		return h.JWK.PublicKey()
	})
	if err != nil {
		return Verified{}, fmt.Errorf("%w: %w", ErrInvalid, err)
	}
	jkt, err := h.JWK.Thumbprint()
	if err != nil {
		return Verified{}, fmt.Errorf("%w: %w", ErrInvalid, err)
	}

	c, err := parseClaims(payload)
	if err != nil {
		return Verified{}, err
	}

	if c.HTM != want.Method {
		return Verified{}, fmt.Errorf("%w: htm", ErrMismatch)
	}
	htu, err := NormalizeURI(c.HTU)
	if err != nil {
		return Verified{}, fmt.Errorf("%w: htu", ErrInvalid)
	}
	wantURI, err := NormalizeURI(want.URI)
	if err != nil || htu != wantURI {
		return Verified{}, fmt.Errorf("%w: htu", ErrMismatch)
	}

	if c.IAT.After(now.Add(policy.Skew)) {
		return Verified{}, fmt.Errorf("%w: iat in the future", ErrInvalid)
	}
	notAfter := c.IAT.Add(policy.Lifespan + policy.Skew)
	if now.After(notAfter) {
		return Verified{}, fmt.Errorf("%w: proof expired", ErrInvalid)
	}

	// ath binds the proof to exactly one token: required when one is expected, refused when none is.
	if want.AccessToken != "" {
		digest := sha256.Sum256([]byte(want.AccessToken))
		if !equal(c.ATH, base64.RawURLEncoding.EncodeToString(digest[:])) {
			return Verified{}, fmt.Errorf("%w: ath", ErrMismatch)
		}
	} else if c.ATH != "" {
		return Verified{}, fmt.Errorf("%w: ath without an access token", ErrMismatch)
	}
	if want.JKT != "" && !equal(jkt, want.JKT) {
		return Verified{}, ErrKeyMismatch
	}
	if want.Nonce != "" && !equal(c.Nonce, want.Nonce) {
		return Verified{}, fmt.Errorf("%w: nonce", ErrMismatch)
	}

	fresh, err := store.TryUse(ctx, replay.Use{JKT: jkt, Method: c.HTM, URI: htu, JTI: c.JTI, NotAfter: notAfter})
	if err != nil {
		return Verified{}, withContextCause(errReplayCheck, err)
	}
	if !fresh {
		return Verified{}, ErrReplayed
	}
	return Verified{JKT: jkt, Claims: c, NotAfter: notAfter}, nil
}

// errReplayCheck is a replay store that could not answer; the proof is refused.
var errReplayCheck = errors.New("dpop: replay check failed")

// errURI is any htu that is not an absolute http(s) URI. It never carries the input.
var errURI = errors.New("dpop: not an absolute http(s) URI")

// NormalizeURI is the htu comparison form (RFC 9449 4.3, RFC 3986 6.2.2-6.2.3): an absolute http or
// https URI with lowercase scheme and host, without the default port, query, fragment or userinfo,
// with an empty path as "/", and the path normalised by normalizePath.
func NormalizeURI(raw string) (string, error) {
	u, err := url.Parse(raw)
	if err != nil {
		return "", errURI
	}
	scheme := strings.ToLower(u.Scheme)
	if (scheme != "http" && scheme != "https") || u.Host == "" || u.User != nil || u.Opaque != "" {
		return "", errURI
	}
	host, port := strings.ToLower(u.Hostname()), u.Port()
	if host == "" {
		return "", errURI
	}
	if (scheme == "http" && port == "80") || (scheme == "https" && port == "443") {
		port = ""
	}
	if strings.Contains(host, ":") {
		host = "[" + host + "]"
	}
	if port != "" {
		host += ":" + port
	}
	path, err := normalizePath(u.EscapedPath())
	if err != nil {
		return "", errURI
	}
	return scheme + "://" + host + path, nil
}

// normalizePath applies RFC 3986 6.2.2 to an escaped path: percent escapes in uppercase hex,
// percent-encoded unreserved characters decoded, then remove_dot_segments (5.2.4). Escaped reserved
// characters stay escaped (%2F is not /), and repeated and trailing slashes are kept.
func normalizePath(escaped string) (string, error) {
	var b strings.Builder
	for i := 0; i < len(escaped); i++ {
		c := escaped[i]
		if c != '%' {
			b.WriteByte(c)
			continue
		}
		if i+2 >= len(escaped) || !isHex(escaped[i+1]) || !isHex(escaped[i+2]) {
			return "", errURI
		}
		v := unhex(escaped[i+1])<<4 | unhex(escaped[i+2])
		if isUnreserved(v) {
			b.WriteByte(v)
		} else {
			b.WriteString("%" + strings.ToUpper(escaped[i+1:i+3]))
		}
		i += 2
	}
	path := removeDotSegments(b.String())
	if path == "" {
		path = "/"
	}
	return path, nil
}

// removeDotSegments is RFC 3986 5.2.4.
func removeDotSegments(in string) string {
	var out []string // output segments, each with its leading "/" where it had one
	for in != "" {
		switch {
		case strings.HasPrefix(in, "../"):
			in = in[3:]
		case strings.HasPrefix(in, "./"):
			in = in[2:]
		case strings.HasPrefix(in, "/./"):
			in = in[2:]
		case in == "/.":
			in = "/"
		case strings.HasPrefix(in, "/../"):
			in = in[3:]
			if len(out) > 0 {
				out = out[:len(out)-1]
			}
		case in == "/..":
			in = "/"
			if len(out) > 0 {
				out = out[:len(out)-1]
			}
		case in == "." || in == "..":
			in = ""
		default:
			end := strings.IndexByte(in[1:], '/') + 1
			if end == 0 {
				end = len(in)
			}
			out = append(out, in[:end])
			in = in[end:]
		}
	}
	return strings.Join(out, "")
}

func isUnreserved(c byte) bool {
	return c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-' || c == '.' || c == '_' || c == '~'
}

func isHex(c byte) bool { return c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F' }

func unhex(c byte) byte {
	switch {
	case c >= 'a':
		return c - 'a' + 10
	case c >= 'A':
		return c - 'A' + 10
	}
	return c - '0'
}

// withContextCause returns err, plus the context cancellation or deadline inside cause if there is
// one; nothing else of cause is kept, since a store's error may carry anything.
func withContextCause(err, cause error) error {
	for _, c := range []error{context.Canceled, context.DeadlineExceeded} {
		if errors.Is(cause, c) {
			return fmt.Errorf("%w: %w", err, c)
		}
	}
	return err
}

const (
	maxProofSize = 8 << 10
	maxJTI       = 256
)

type wireClaims struct {
	JTI   string `json:"jti"`
	HTM   string `json:"htm"`
	HTU   string `json:"htu"`
	IAT   int64  `json:"iat"`
	ATH   string `json:"ath,omitempty"`
	Nonce string `json:"nonce,omitempty"`
}

func parseClaims(payload []byte) (Claims, error) {
	members, err := jose.ParseObject(payload)
	if err != nil {
		return Claims{}, fmt.Errorf("%w: %w", ErrInvalid, err)
	}
	var c Claims
	for _, f := range []struct {
		name     string
		dst      *string
		required bool
	}{{"jti", &c.JTI, true}, {"htm", &c.HTM, true}, {"htu", &c.HTU, true}, {"ath", &c.ATH, false}, {"nonce", &c.Nonce, false}} {
		v, present, ok := jose.String(members, f.name)
		if (present && !ok) || (f.required && v == "") {
			return Claims{}, fmt.Errorf("%w: claim %s", ErrInvalid, f.name)
		}
		*f.dst = v
	}
	if len(c.JTI) > maxJTI {
		return Claims{}, fmt.Errorf("%w: jti too long", ErrInvalid)
	}
	// ponytail: iat must be an integer; a fractional NumericDate is refused, none of our minters emit one.
	iat, err := strconv.ParseInt(string(bytes.TrimSpace(members["iat"])), 10, 64)
	if err != nil || iat <= 0 {
		return Claims{}, fmt.Errorf("%w: claim iat", ErrInvalid)
	}
	c.IAT = time.Unix(iat, 0)
	return c, nil
}

func equal(a, b string) bool { return subtle.ConstantTimeCompare([]byte(a), []byte(b)) == 1 }
